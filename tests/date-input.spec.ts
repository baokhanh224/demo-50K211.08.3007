import { test, expect } from "@playwright/test";
import { installTrustedTransport } from "./public-transport";

test("Dates: automatic slashes, caret editing, paste and calendar work across the app", async ({ page, context }) => {
  if (process.env.BASE_URL?.startsWith("https:")) await installTrustedTransport(context);
  await page.goto("/");
  await page.getByLabel("Tên đăng nhập", { exact: true }).fill(process.env.DEMO_USERNAME!);
  await page.getByLabel("Mật khẩu", { exact: true }).fill(process.env.DEMO_PASSWORD!);
  await page.getByRole("button", { name: "Đăng nhập", exact: true }).click();
  await expect(page.locator(".sidebar")).toBeVisible();
  const data = await page.evaluate(async () => (await fetch("/api/bootstrap")).json());
  await page.getByRole("link", { name: "Quản lý tồn kho", exact: true }).click();
  const product = data.products.find((p: any) => p.expiry_managed);
  expect(product).toBeTruthy();
  await page.getByLabel("Tìm kiếm sản phẩm", { exact: true }).fill(product.id);
  await page.locator(".suggestions button").filter({ hasText: product.id }).click();
  const expiry = page.getByLabel("Hạn sử dụng", { exact: true });
  await expiry.pressSequentially("14", { delay: 25 }); await expect(expiry).toHaveValue("14/");
  await expiry.pressSequentially("05", { delay: 25 }); await expect(expiry).toHaveValue("14/05/");
  await expiry.pressSequentially("2026", { delay: 25 }); await expect(expiry).toHaveValue("14/05/2026");
  await expiry.press("Backspace"); await expect(expiry).toHaveValue("14/05/202");
  await expiry.fill("14/05/2026");
  await expiry.evaluate((n: HTMLInputElement) => n.setSelectionRange(3, 5));
  await expiry.pressSequentially("06", { delay: 25 }); await expect(expiry).toHaveValue("14/06/2026");
  await expiry.press("Backspace"); await expect(expiry).toHaveValue("14/0/2026");
  await expiry.press("5"); await expect(expiry).toHaveValue("14/05/2026");
  await expiry.fill("14/"); await expiry.press("End"); await expiry.press("Backspace");
  await expect(expiry).toHaveValue("1"); await expiry.press("Backspace"); await expect(expiry).toHaveValue("");
  await expiry.fill("1/5/2026"); await expect(expiry).toHaveValue("01/05/2026");
  await expiry.fill("2026-05-14"); await expect(expiry).toHaveValue("14/05/2026");
  await page.getByRole("link", { name: "Quản lý sản phẩm", exact: true }).click();
  await page.getByRole("button", { name: "Thêm sản phẩm", exact: true }).click();
  const form = page.getByRole("dialog", { name: "Thêm sản phẩm", exact: true });
  await form.getByPlaceholder("dd/mm/yyyy", { exact: true }).fill("31122027");
  await expect(form.getByPlaceholder("dd/mm/yyyy", { exact: true })).toHaveValue("31/12/2027");
  await expect(form.getByLabel("Chọn hạn sử dụng", { exact: true })).toHaveValue("2027-12-31");
  await form.getByRole("button", { name: "Hủy", exact: true }).click();
  await page.getByRole("dialog", { name: "Xác nhận", exact: true }).getByRole("button", { name: "Xác nhận", exact: true }).click();
  await page.getByRole("link", { name: "Báo cáo thống kê", exact: true }).click();
  await page.getByLabel("Từ ngày", { exact: true }).fill("14052026");
  await expect(page.getByLabel("Từ ngày", { exact: true })).toHaveValue("14/05/2026");
  await page.getByRole("button", { name: "Mở lịch từ ngày", exact: true }).click();
  await page.getByRole("dialog", { name: "Lịch từ ngày", exact: true }).getByRole("button", { name: "15/05/2026", exact: true }).click();
  await expect(page.getByLabel("Từ ngày", { exact: true })).toHaveValue("15/05/2026");
  await expect(page.getByLabel("Từ ngày", { exact: true })).toBeFocused();
  await page.getByRole("link", { name: "Tra cứu lịch sử bán hàng", exact: true }).click();
  await page.getByLabel("Từ ngày", { exact: true }).fill("14052026");
  await page.getByLabel("Đến ngày", { exact: true }).fill("15052026");
  await expect(page.getByLabel("Từ ngày", { exact: true })).toHaveValue("14/05/2026");
  await expect(page.getByLabel("Đến ngày", { exact: true })).toHaveValue("15/05/2026");
});
