import { test, expect } from "@playwright/test";
import { installTrustedTransport } from "./public-transport";
import { sortCategories } from "../lib/categories";

test("shared categories in products, suppliers and reports; only supplier Other accepts new text", async ({ page, context }) => {
  if (process.env.BASE_URL?.startsWith("https:")) await installTrustedTransport(context);
  await page.setViewportSize({ width: 1440, height: 927 });
  await page.goto("/");
  await expect(page.getByRole("button", { name: "Đăng nhập", exact: true })).toBeEnabled();
  await page.getByLabel("Tên đăng nhập", { exact: true }).fill(process.env.DEMO_USERNAME!);
  await page.getByLabel("Mật khẩu", { exact: true }).fill(process.env.DEMO_PASSWORD!);
  await page.getByRole("button", { name: "Đăng nhập", exact: true }).click();
  await expect(page.locator(".sidebar")).toBeVisible();
  const data = await page.evaluate(async () => (await fetch("/api/bootstrap")).json());
  expect(data.product_categories).toEqual(data.categories);
  const custom = { id: 987654, name: "Đồ đông lạnh và thực phẩm chế biến dành cho gia đình có tên danh mục rất dài" };
  const categories = sortCategories([...data.categories, custom]);
  const otherId = categories.find(c => c.name === "Khác")!.id;
  const supplier = data.suppliers[0];
  await page.route("**/api/bootstrap", r => r.fulfill({ json: { ...data, categories, product_categories: categories,
    suppliers: data.suppliers.map((s: any) => s.id === supplier.id ? { ...s, category_ids: [otherId], categories: ["Khác"] } : s) } }));
  await page.reload(); await expect(page.locator(".sidebar")).toBeVisible();
  const names = categories.map(c => c.name);
  await page.getByRole("link", { name: "Quản lý sản phẩm", exact: true }).click();
  await page.locator(".product-controls").getByRole("button", { name: "Danh mục", exact: true }).click();
  await expect(page.locator(".product-controls [role=option]")).toHaveText(["Tất cả", ...names]);
  await page.locator(".product-controls").getByRole("option", { name: custom.name, exact: true }).click();
  const categoryButton = page.locator(".product-controls").getByRole("button", { name: "Danh mục", exact: true });
  await expect(categoryButton).toHaveAttribute("title", custom.name);
  await expect(categoryButton.locator(".product-select-value")).toHaveCSS("text-overflow", "ellipsis");
  const geometry = await categoryButton.evaluate(el => {
    const box = el.getBoundingClientRect(), arrow = el.querySelector("img")!.getBoundingClientRect();
    const text = el.querySelector(".product-select-value")!;
    return { contained: el.scrollWidth <= el.clientWidth, arrowContained: arrow.right <= box.right, truncated: text.scrollWidth > text.clientWidth };
  });
  expect(geometry).toEqual({ contained: true, arrowContained: true, truncated: true });
  await categoryButton.click();
  await page.locator(".product-controls").getByRole("option", { name: "Tất cả", exact: true }).click();
  await page.getByRole("button", { name: "Thêm sản phẩm", exact: true }).click();
  const product = page.getByRole("dialog", { name: "Thêm sản phẩm", exact: true });
  await product.getByRole("button", { name: "Danh mục", exact: true }).click();
  await expect(product.getByRole("option", { name: custom.name, exact: true })).toBeVisible();
  await product.getByRole("option", { name: "Khác", exact: true }).click();
  await expect(product.getByPlaceholder("Nhập tên danh mục mới", { exact: true })).toHaveCount(0);
  await product.getByRole("button", { name: "Hủy", exact: true }).click();
  await page.getByRole("dialog", { name: "Xác nhận", exact: true }).getByRole("button", { name: "Xác nhận", exact: true }).click();
  await page.getByRole("link", { name: "Quản lý nhà cung cấp", exact: true }).click();
  await page.locator(".supplier-filters").getByRole("button", { name: "Danh mục", exact: true }).click();
  await expect(page.locator(".supplier-filters [role=option]")).toHaveText(["Tất cả", ...names]);
  await page.locator(".supplier-filters").getByRole("button", { name: "Danh mục", exact: true }).click();
  await page.getByRole("button", { name: "Thêm nhà cung cấp", exact: true }).click();
  const form = page.getByRole("dialog", { name: "Thêm nhà cung cấp", exact: true });
  await form.getByRole("button", { name: "Danh mục", exact: true }).click();
  const menu = form.getByRole("dialog", { name: "Chọn danh mục", exact: true });
  await expect(menu.locator("label")).toHaveText(names);
  await menu.getByLabel("Khác", { exact: true }).click();
  const input = form.getByPlaceholder("Nhập tên danh mục mới", { exact: true });
  await expect(input).toBeVisible(); await input.fill(custom.name); await input.press("Enter");
  await expect(form.getByText("Danh mục đã tồn tại, vui lòng chọn danh mục có sẵn!", { exact: true })).toBeVisible();
  await form.getByRole("button", { name: "Hủy", exact: true }).click();
  await page.getByRole("dialog", { name: "Xác nhận", exact: true }).getByRole("button", { name: "Xác nhận", exact: true }).click();
  await page.getByLabel("Chọn " + supplier.id, { exact: true }).check();
  await page.getByRole("button", { name: "Sửa", exact: true }).click();
  const edit = page.getByRole("dialog", { name: "Sửa thông tin nhà cung cấp", exact: true });
  await edit.getByRole("button", { name: "Danh mục", exact: true }).click();
  const existing = edit.getByRole("dialog", { name: "Chọn danh mục", exact: true });
  await expect(existing.getByLabel("Khác", { exact: true })).toBeChecked();
  await expect(existing.getByText("Khác (có sẵn)", { exact: true })).toHaveCount(0);
  await existing.getByLabel("Khác", { exact: true }).click();
  await expect(edit.locator(".supplier-chip")).toHaveCount(0);
  await edit.getByRole("button", { name: "Hủy", exact: true }).click();
  await page.getByRole("dialog", { name: "Xác nhận", exact: true }).getByRole("button", { name: "Xác nhận", exact: true }).click();
  await page.getByRole("link", { name: "Báo cáo thống kê", exact: true }).click();
  await page.getByRole("button", { name: "Sản phẩm / nhóm sản phẩm (không bắt buộc)", exact: true }).click();
  const reports = page.getByRole("dialog", { name: "Chọn sản phẩm / nhóm sản phẩm", exact: true });
  const group = reports.locator(".report-options > div").first();
  await expect(group.locator("label")).toHaveText(["Tất cả", ...names]);
  await expect(reports.getByPlaceholder("Nhập tên danh mục mới", { exact: true })).toHaveCount(0);
});
